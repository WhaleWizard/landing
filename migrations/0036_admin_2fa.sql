-- Двухфакторный вход в админку: пароль плюс одноразовый код из приложения
-- (Google Authenticator и любое совместимое).
--
-- Почему это отдельная таблица, а не переменная окружения: секрет создаётся
-- в самой админке при настройке, а переменную в Cloudflare Pages нельзя
-- поменять без пересборки сайта.
--
-- Одна строка на весь сайт (`id = 1`): администратор здесь один, общий пароль
-- никуда не делся. CHECK не даёт случайно завести вторую конфигурацию, из-за
-- которой было бы неясно, какой секрет настоящий.
CREATE TABLE IF NOT EXISTS admin_2fa (
  id INTEGER PRIMARY KEY CHECK (id = 1),

  -- Секрет TOTP в base32. Он же лежит в приложении на телефоне.
  totp_secret TEXT NOT NULL,

  -- Пока NULL, защита настроена, но не включена: секрет создан и показан, а
  -- подтверждающий код ещё не введён. Так неудачная настройка не запирает
  -- вход.
  enabled_at INTEGER,

  -- Хеши резервных кодов (SHA-256), JSON-массивом. Сами коды показываются
  -- один раз при включении и в базе не хранятся: из хеша код не восстановить,
  -- поэтому доступ к D1 не даёт входа.
  backup_codes TEXT NOT NULL DEFAULT '[]',

  -- Номер 30-секундного интервала, по которому уже входили. Не даёт
  -- использовать один и тот же код дважды, пока он не истёк.
  last_step INTEGER NOT NULL DEFAULT 0,

  created_at INTEGER NOT NULL DEFAULT (strftime('%s','now')),
  updated_at INTEGER NOT NULL DEFAULT (strftime('%s','now'))
);

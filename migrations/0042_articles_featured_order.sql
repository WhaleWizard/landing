-- Закреплённые статьи на главной.
--
-- Что было: блок «Статьи» на главной показывал весь блог подряд в порядке
-- добавления. При тринадцати статьях это терпимо, при шестистах — карусель
-- из шестисот карточек. Теперь владелец выбирает до пятнадцати статей и их
-- порядок; пока не выбрал ничего, показываются пятнадцать последних.
--
-- Почему колонка, а не отдельная таблица: закрепление — свойство статьи,
-- у одной статьи один порядковый номер, и читается он тем же запросом, что
-- и карточка. Пусто — значит не закреплена. Порядок 1..15 задаёт админка
-- одним запросом на весь список, поэтому дыр и дублей в нумерации не бывает.
ALTER TABLE articles ADD COLUMN featured_order INTEGER;

-- Индекс частичный: незакреплённые строки в нём не лежат и места не занимают.
CREATE INDEX IF NOT EXISTS idx_articles_featured_order
  ON articles(featured_order) WHERE featured_order IS NOT NULL;

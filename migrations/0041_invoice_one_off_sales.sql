-- Разовые продажи в «Финансах»: консультация, аудит, настройка под ключ.
--
-- Что было: раздел умел записывать только абонентку по карточке клиента.
-- Консультация за $70 — это разовая продажа человеку, которого заводить в
-- «Клиенты» незачем: он пришёл, получил разбор и ушёл. Записать её было
-- некуда, и такие деньги в итогах месяца просто не появлялись.
--
-- Почему не отдельная таблица: это тот же приход денег, что и счёт. Отдельная
-- таблица потребовала бы вторых итогов, второй сортировки и второго места, где
-- легко забыть про валюту. Здесь добавлены две колонки к тому же счёту.
--
-- `kind` — за что деньги. Без него разовые продажи неотличимы от абонентки, и
-- вопрос «сколько консультаций я продал за месяц» остаётся без ответа.
-- Старые счета остаются абоненткой: DEFAULT 'retainer' описывает их верно.
ALTER TABLE invoices ADD COLUMN kind TEXT NOT NULL DEFAULT 'retainer';

-- `payer` — имя или контакт разового покупателя. У счёта по абонентке имя
-- берётся из карточки клиента, а у консультации карточки нет: без этого поля
-- в списке стояло бы «без клиента» и вспомнить, кому именно продана
-- консультация, было бы нельзя.
ALTER TABLE invoices ADD COLUMN payer TEXT NOT NULL DEFAULT '';

-- Разрезы «сколько консультаций за месяц» и «что оплачено» читаются по этим
-- двум колонкам, поэтому у них свой индекс.
CREATE INDEX IF NOT EXISTS idx_invoices_kind ON invoices(kind, period DESC);

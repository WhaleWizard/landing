-- Скрытое уведомление не возвращается, пока повод тот же.
--
-- Что было: кнопка «×» в центре уведомлений ставила `resolved_at`, и запись
-- выглядела так же, как повод, который исчез сам. Следующая проверка видела
-- «ситуация есть, открытой записи нет» и оживляла её — скрытое уведомление
-- возвращалось через минуту и снова уходило в Telegram.
--
-- Теперь «скрыто владельцем» помечается отдельно. Пока ситуация остаётся,
-- запись молчит: текст обновляется, но в список и в Telegram она не идёт.
-- Отметка снимается сама, когда повод исчезает, — вернувшаяся ситуация
-- оживёт как новая и один раз уйдёт в Telegram.
--
-- Почему колонка, а не отдельная таблица: скрытие — свойство самой записи
-- с её `fingerprint`, и читается оно тем же запросом, что и состояние.
-- Без миграции раздел не падает: скрытие работает по-старому, через
-- `resolved_at` (проверка через PRAGMA в functions/_lib/admin-alerts.ts).
ALTER TABLE admin_alerts ADD COLUMN dismissed_at TEXT;

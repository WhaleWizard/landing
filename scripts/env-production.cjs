// Подключается через `node --require` перед генератором страниц: React и
// motion выбирают сборку по NODE_ENV при первом импорте, а импорты в ESM
// поднимаются выше любого кода файла — задать переменную изнутри нельзя.
// Продакшен-сборка быстрее и не пишет в лог предупреждения, которые относятся
// только к разработке.
if (!process.env.NODE_ENV) process.env.NODE_ENV = 'production';

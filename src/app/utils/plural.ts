/**
 * Русское согласование существительного с числом.
 *
 * Правило простое, но ошибаются в нём постоянно: «1 заявок», «2 файлов»,
 * «21 дело — начни с них». В админке это видно каждый день, и небрежность в
 * счётчиках читается как небрежность во всём разделе.
 *
 * Копий этого правила в проекте было четыре — в «Сегодня», в «Доступе к
 * страницам», на странице кейсов и в автооценке лида, — записанных двумя
 * разными способами. Для неотрицательных чисел они давали одно и то же, но
 * расходились на отрицательных, и каждая новая надпись начиналась с выбора,
 * какую копию скопировать. Теперь копия одна.
 *
 * Формы задаются в порядке «1 / 2 / 5»: `['заявка', 'заявки', 'заявок']`.
 */
export function plural(count: number, forms: [one: string, few: string, many: string]): string {
  const abs = Math.abs(count) % 100;
  const tail = abs % 10;
  if (abs > 10 && abs < 20) return forms[2];
  if (tail > 1 && tail < 5) return forms[1];
  if (tail === 1) return forms[0];
  return forms[2];
}

/** Число вместе с согласованным словом: «5 заявок», «1 заявка». */
export function withPlural(count: number, forms: [one: string, few: string, many: string]): string {
  return `${count} ${plural(count, forms)}`;
}

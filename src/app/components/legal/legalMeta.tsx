/**
 * Дата редакции юридических документов — одной строкой на весь сайт.
 *
 * Дата была прописана руками в трёх страницах-обёртках (`/offer`,
 * `/privacy-policy`, `/cookie-policy`), а те же тексты показываются ещё и в
 * окнах: из формы заявки, из лендинговой формы и из настроек cookie. В окне
 * даты не было вовсе — то есть человек видел документ без редакции ровно в
 * тот момент, когда с ним соглашался.
 *
 * Вместе с каждой заявкой сохраняется квитанция согласия. Без даты в самом
 * документе привязать квитанцию к тексту нечем: если текст поменяется,
 * доказать, с чем именно согласился человек, будет нельзя.
 *
 * Меняете текст любого документа — меняете дату здесь, и она обновится
 * сразу во всех шести местах.
 */
export const LEGAL_UPDATED_AT = '29 мая 2026 г.';

/** Строка «Дата последнего обновления» для окон, где нет заголовка страницы. */
export function LegalUpdatedAt({ className = '' }: { className?: string }) {
  return (
    <p className={`text-sm text-muted-foreground ${className}`.trim()}>
      Дата последнего обновления: {LEGAL_UPDATED_AT}
    </p>
  );
}
